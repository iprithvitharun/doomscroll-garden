// Bakes art/atlas.png, src/atlas.js and icons/*.png from tools/sprites.
// Needs Google Chrome. Usage: node tools/bake.mjs   (from the repo root)
import { spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tools = join(root, 'tools');
const sleep = ms => new Promise(r => setTimeout(r, ms));

// tiny static server for tools/ (canvas pixel reads need http, not file://)
const server = createServer((req, res) => {
  try {
    const p = join(tools, decodeURIComponent(new URL(req.url, 'http://x').pathname));
    if (!p.startsWith(tools)) throw new Error('outside');
    const body = readFileSync(p);
    res.writeHead(200, { 'content-type': extname(p) === '.html' ? 'text/html' : 'image/png' });
    res.end(body);
  } catch { res.writeHead(404); res.end(); }
}).listen(0, '127.0.0.1');
await new Promise(r => server.once('listening', r));
const port = server.address().port;

const dbg = 9300 + Math.floor(Math.random() * 400);
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', [
  '--headless=new', `--remote-debugging-port=${dbg}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), 'dg-bake-'))}`, '--no-first-run', 'about:blank',
], { stdio: 'ignore' });
try {
  let target;
  for (let i = 0; i < 60 && !target; i++) { await sleep(250); try { target = (await (await fetch(`http://127.0.0.1:${dbg}/json/list`)).json()).find(t => t.type === 'page'); } catch {} }
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise(r => ws.addEventListener('open', r, { once: true }));
  let id = 0; const pending = new Map();
  ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
  const send = (method, params = {}) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
  await send('Page.enable');
  await send('Page.navigate', { url: `http://127.0.0.1:${port}/bake.html` });
  await sleep(800);
  const r = await send('Runtime.evaluate', { expression: 'bake().then(JSON.stringify)', awaitPromise: true, returnByValue: true });
  if (r.result.exceptionDetails) throw new Error(JSON.stringify(r.result.exceptionDetails));
  const out = JSON.parse(r.result.result.value);
  const png = d => Buffer.from(d.split(',')[1], 'base64');
  writeFileSync(join(root, 'art/atlas.png'), png(out.atlas));
  writeFileSync(join(root, 'src/atlas.js'), `// Generated by tools/bake.mjs: sprite -> [x, y, w, h, anchorX, anchorY] at growth sizes 50%, 75%, 100%.\nglobalThis.DG = globalThis.DG || {};\nDG.ATLAS = ${JSON.stringify(out.map)};\n`);
  for (const [s, d] of Object.entries(out.icons)) writeFileSync(join(root, `icons/icon${s}.png`), png(d));
  console.log('atlas', out.size.join('x'), 'sprites', Object.keys(out.map).length);
  ws.close();
} finally { chrome.kill(); server.close(); }
